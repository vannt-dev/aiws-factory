const exists = (root, rel) => fs.existsSync(path.join(root, rel));
const inPhase = (phase, extra = {}) => ({ AIWS_REQ: 'REQ-001', AIWS_PHASE: phase, ...extra });

/** The frontmatter and the body of a generated Markdown agent. */
function split(text) {
  assert.ok(text.startsWith('---\n'), text.slice(0, 40));
  const end = text.indexOf('\n---\n', 4);
  return { front: text.slice(4, end), body: text.slice(end + 5) };
}

test('sync opencode: one subagent an agent with its own permissions, the skills, and a plugin that asks the guard', () => {
  const root = makeWorkspace();
  const out = ok(root, ['sync', 'opencode']).stdout;
  assert.match(out, /Generated for opencode:/);

  const developer = split(readFile(root, '.opencode/agents/developer.md'));
  assert.match(developer.front, /^description: ".+"$/m);
  assert.match(developer.front, /^mode: subagent$/m);
  assert.match(developer.front, /^permission:\n {2}edit: allow\n {2}bash: ask$/m);
  assert.match(developer.body, /GENERATED by `aiws sync opencode`/);
  // the agent's own instructions, where its skills are, and what checks it
  assert.ok(developer.body.includes(readFile(root, 'aiws/agents/developer.md').split('\n---\n')[1].trim().split('\n')[0]));
  assert.match(developer.body, /\.agents\/skills\/unit-testing\/SKILL\.md/);
  assert.match(developer.body, /aiws guard/);

  // a contract without a shell has none; one without a write tool cannot edit
  const reviewer = split(readFile(root, '.opencode/agents/reviewer.md'));
  assert.match(reviewer.front, /^permission:\n {2}edit: allow\n {2}bash: deny$/m);
  writeFile(root, 'aiws/agents/auditor.md', '---\ndescription: Reads and reports.\ntools: [read]\nskills: []\n---\nYou only read.\n');
  // files of the project's own are not the kit's to remove; one the kit wrote for an agent that is gone is
  writeFile(root, '.opencode/agents/mine.md', '---\ndescription: mine\n---\nMine.\n');
  ok(root, ['sync', 'opencode']);
  assert.match(split(readFile(root, '.opencode/agents/auditor.md')).front, /^permission:\n {2}edit: deny\n {2}bash: deny$/m);
  fs.rmSync(path.join(root, 'aiws/agents/auditor.md'));
  ok(root, ['sync', 'opencode']);
  assert.ok(!exists(root, '.opencode/agents/auditor.md'));
  assert.equal(readFile(root, '.opencode/agents/mine.md'), '---\ndescription: mine\n---\nMine.\n');

  // skills where OpenCode, Codex and Antigravity all read them
  assert.equal(readFile(root, '.agents/skills/unit-testing/SKILL.md'), readFile(root, 'aiws/skills/unit-testing/SKILL.md'));
  assert.ok(exists(root, '.opencode/plugins/aiws-guard.js'));
});

test('sync opencode: the plugin lets the guard decide, and refuses what the guard refuses', async () => {
  const root = makeWorkspace({ discover: true });
  ok(root, ['new', 'REQ-001']);
  ok(root, ['sync', 'opencode']);
  const abs = (p) => path.join(root, p);

  // the plugin runs `aiws guard` in a child process: the phase is in the environment of that process
  const driver = path.join(root, 'driver.mjs');
  fs.writeFileSync(
    driver,
    `import { AiwsGuard } from ${JSON.stringify(pathToFileURL(abs('.opencode/plugins/aiws-guard.js')).href)};
const hooks = await AiwsGuard({ directory: '/', worktree: '/' });
const before = hooks['tool.execute.before'];
const cases = JSON.parse(process.argv[2]);
const outcome = {};
for (const [name, [tool, args]] of Object.entries(cases)) {
  try { await before({ tool }, { args }); outcome[name] = null; }
  catch (error) { outcome[name] = error.message; }
}
console.log(JSON.stringify(outcome));
`
  );
  const cases = {
    inScope: ['write', { filePath: abs('aiws/work/REQ-001/01-analysis.md') }],
    outOfScope: ['edit', { filePath: abs('source-be/src/users.js') }],
    secret: ['read', { filePath: abs('source-be/.env') }],
    approve: ['bash', { command: 'aiws approve REQ-001 --gate design' }],
    build: ['bash', { command: 'git status' }],
    other: ['webfetch', { url: 'https://example.com' }],
  };
  const run = (env) => {
    // the test's own CLI stands for the one on PATH
    const r = spawnSync(process.execPath, [driver, JSON.stringify(cases)], {
      cwd: root,
      encoding: 'utf8',
      env: cleanEnv({ AIWS_GUARD_COMMAND: `"${process.execPath}" "${path.resolve('bin', 'aiws.js')}" guard`, ...env }),
    });
    assert.equal(r.status, 0, r.stderr);
    return JSON.parse(r.stdout.trim().split('\n').pop());
  };
  const analysis = run(inPhase('analysis'));
  assert.equal(analysis.inScope, null);
  assert.match(analysis.outOfScope, /outside the write scope of phase 'analysis'/);
  assert.match(analysis.secret, /AIWS/);
  assert.match(analysis.approve, /AIWS/);
  assert.equal(analysis.other, null, 'a tool the guard has no rule for is not its business');
  // a session that works on no requirement: off the requirement's branch, which the guard reads as well
  git(root, ['checkout', '-q', 'main']);
  const plain = run({});
  assert.equal(plain.outOfScope, null);
  assert.equal(plain.build, null);
  assert.match(plain.approve, /AIWS/, 'an AI may never approve, in any session');
});

test('sync antigravity: one agent a folder, the skills, and a hook that keeps the hooks of others', () => {
  const root = makeWorkspace();
  writeFile(
    root,
    '.agents/hooks.json',
    JSON.stringify({ 'someone-else': { PreToolUse: [{ matcher: 'run_command', hooks: [{ type: 'command', command: 'x' }] }] } })
  );
  writeFile(root, '.agents/agents/mine/agent.md', '---\nname: mine\ndescription: mine\n---\nMine.\n');
  ok(root, ['sync', 'antigravity']);

  const developer = split(readFile(root, '.agents/agents/developer/agent.md'));
  assert.match(developer.front, /^name: developer$/m);
  assert.match(developer.front, /^description: ".+"$/m);
  assert.match(developer.body, /GENERATED by `aiws sync antigravity`/);
  assert.match(developer.body, /\.agents\/skills\/unit-testing\/SKILL\.md/);
  assert.ok(exists(root, '.agents/agents/mine/agent.md'));
  assert.ok(exists(root, '.agents/skills/unit-testing/SKILL.md'));

  const hooks = JSON.parse(readFile(root, '.agents/hooks.json'));
  assert.deepEqual(Object.keys(hooks).sort(), ['aiws-guard', 'someone-else']);
  const [entry] = hooks['aiws-guard'].PreToolUse;
  for (const tool of ['run_command', 'view_file', 'write_to_file', 'replace_file_content', 'multi_replace_file_content']) {
    assert.ok(entry.matcher.split('|').includes(tool), tool);
  }
  // Antigravity starts a hook in `.agents/`; this workspace has no CLI of its own, so the one on PATH
  assert.deepEqual(entry.hooks, [{ type: 'command', command: 'aiws guard --from antigravity', timeout: 30 }]);

  // a workspace that carries the CLI runs that one, by a path that holds from `.agents/`
  fs.mkdirSync(path.join(root, 'aiws/adapters/cli/bin'), { recursive: true });
  fs.writeFileSync(path.join(root, 'aiws/adapters/cli/bin/aiws.js'), '');
  ok(root, ['sync', 'antigravity']);
  const own = JSON.parse(readFile(root, '.agents/hooks.json'))['aiws-guard'].PreToolUse[0].hooks[0].command;
  assert.equal(own, 'node ../aiws/adapters/cli/bin/aiws.js guard --from antigravity');
});

test('guard --from antigravity: reads the call as Antigravity sends it and answers as it expects', () => {
  const root = makeWorkspace({ discover: true });
  ok(root, ['new', 'REQ-001']);
  const abs = (p) => path.join(root, p);
  // as Antigravity 1.2.9 sends them, from the folder it starts a hook in
  const call = (name, args) => ({
    conversationId: 'c',
    workspacePaths: [root],
    stepIdx: 2,
    toolCall: { name, args: { ...args, toolAction: 'x', toolSummary: 'y' } },
  });
  const hook = (payload, env = {}) => {
    fs.mkdirSync(abs('.agents'), { recursive: true });
    const r = spawnSync(process.execPath, [path.resolve('bin', 'aiws.js'), 'guard', '--from', 'antigravity'], {
      cwd: abs('.agents'),
      encoding: 'utf8',
      env: cleanEnv(env),
      input: typeof payload === 'string' ? payload : JSON.stringify(payload),
    });
    assert.equal(r.status, 0, r.stderr);
    return r.stdout.trim() ? JSON.parse(r.stdout) : null;
  };

  const analysis = inPhase('analysis');
  assert.equal(
    hook(call('write_to_file', { TargetFile: abs('aiws/work/REQ-001/01-analysis.md'), CodeContent: 'x', Overwrite: true }), analysis),
    null
  );
  const edit = hook(
    call('replace_file_content', { TargetFile: abs('source-be/src/users.js'), TargetContent: 'a', ReplacementContent: 'b' }),
    analysis
  );
  assert.equal(edit.decision, 'deny');
  assert.match(edit.reason, /outside the write scope of phase 'analysis'/);
  assert.equal(hook(call('multi_replace_file_content', { TargetFile: abs('source-be/src/users.js') }), analysis).decision, 'deny');
  assert.equal(hook(call('view_file', { AbsolutePath: abs('source-be/.env') }), analysis).decision, 'deny');
  assert.equal(hook(call('view_file', { AbsolutePath: abs('README.md') }), analysis), null);
  assert.equal(hook(call('run_command', { CommandLine: 'aiws approve REQ-001 --gate design', Cwd: root }), analysis).decision, 'deny');
  assert.equal(hook(call('some_other_tool', { Whatever: 1 }), analysis), null);

  // input that is no tool call: refused inside a phase, let through in a session that works on no requirement
  assert.equal(hook('not json', analysis).decision, 'deny');
  assert.equal(hook({ toolCall: 'x' }, analysis).decision, 'deny');
  // off the requirement's branch, which the guard reads as well
  git(root, ['checkout', '-q', 'main']);
  assert.equal(hook('not json'), null);
  assert.equal(hook(call('replace_file_content', { TargetFile: abs('source-be/src/users.js') })), null);
});

test('sync codex: agents as Codex reads them, in a block of config.toml that leaves the rest alone', () => {
  const root = makeWorkspace();
  writeFile(root, '.codex/config.toml', 'model = "gpt-5"\n\n[features]\nweb_search = true\n');
  const out = ok(root, ['sync', 'codex']).stdout;
  assert.match(out, /no guard hook/i);

  const developer = readFile(root, '.codex/agents/developer.toml');
  assert.match(developer, /^# GENERATED by `aiws sync codex`/);
  assert.doesNotMatch(developer, /sandbox_mode/);
  assert.match(developer, /developer_instructions = '''\n[\s\S]+\.agents\/skills\/unit-testing\/SKILL\.md[\s\S]+'''\n/);
  writeFile(
    root,
    'aiws/agents/auditor.md',
    "---\ndescription: Reads and reports.\ntools: [read]\nskills: []\n---\nYou only read. Never write '''three quotes'''.\n"
  );
  ok(root, ['sync', 'codex']);
  const auditor = readFile(root, '.codex/agents/auditor.toml');
  assert.match(auditor, /^sandbox_mode = "read-only"$/m);
  // a body that holds the delimiter is written as a basic string, escaped
  assert.match(auditor, /developer_instructions = """\n/);
  assert.ok(auditor.includes("'''three quotes'''"));

  const config = readFile(root, '.codex/config.toml');
  assert.ok(config.startsWith('model = "gpt-5"\n\n[features]\nweb_search = true\n'), config.slice(0, 80));
  assert.match(
    config,
    /# aiws:begin[^\n]*\n[\s\S]*\[agents\.developer\]\ndescription = ".+"\nconfig_file = "agents\/developer\.toml"\n[\s\S]*# aiws:end\n$/
  );
  assert.equal(config.split('# aiws:begin').length, 2, 'a second sync replaces the block');
  assert.match(config, /\[agents\.auditor\]/);
  fs.rmSync(path.join(root, 'aiws/agents/auditor.md'));
  ok(root, ['sync', 'codex']);
  assert.doesNotMatch(readFile(root, '.codex/config.toml'), /\[agents\.auditor\]/);
  assert.ok(!exists(root, '.codex/agents/auditor.toml'));
  assert.ok(exists(root, '.agents/skills/unit-testing/SKILL.md'));
});

test('sync: an unknown tool is named with the ones there are, and a tool that is only synced cannot run a phase', () => {
  const root = makeWorkspace({ discover: true });
  const unknown = aiws(root, ['sync', 'cursor']);
  assert.notEqual(unknown.status, 0);
  assert.match(unknown.stderr, /Unknown adapter 'cursor'.*claude.*codex.*opencode.*antigravity/);
  assert.match(ok(root, ['help']).stdout, /aiws sync <claude\|codex\|opencode\|antigravity>/);

  ok(root, ['new', 'REQ-001']);
  const run = aiws(root, ['run', 'REQ-001'], { env: { AIWS_ADAPTER: 'opencode' } });
  assert.notEqual(run.status, 0);
  assert.match(run.stderr + run.stdout, /opencode.*interactive sessions.*claude.*codex/s);
});

test("guard: what sync writes for the tools is never an agent's to write, whatever policies.yaml lists", () => {
  const root = makeWorkspace({ discover: true });
  // a workspace whose policies were written before these tools were known
  const file = path.join(root, 'aiws/config/policies.yaml');
  fs.writeFileSync(
    file,
    fs
      .readFileSync(file, 'utf8')
      .split('\n')
      .filter((line) => !/^\s*-\s*\.(?:opencode|agents|codex)\//.test(line))
      .join('\n')
  );
  git(root, ['commit', '-q', '-am', 'older policies', '--allow-empty']);
  ok(root, ['new', 'REQ-001']);
  const write = (rel, env) =>
    aiws(root, ['guard'], {
      input: JSON.stringify({ cwd: root, tool_name: 'Write', tool_input: { file_path: path.join(root, rel) } }),
      env,
    });
  for (const rel of [
    '.opencode/plugins/aiws-guard.js',
    '.agents/hooks.json',
    '.agents/skills/unit-testing/SKILL.md',
    '.codex/config.toml',
    '.claude/settings.json',
  ]) {
    const r = write(rel, inPhase('implementation', { AIWS_TASK: 'T1' }));
    assert.equal(r.status, 2, rel);
    assert.match(r.stderr, /is protected; agents may never write it/, rel);
  }
  // a maintainer keeps the tools' folders of the project in hand
  git(root, ['checkout', '-q', 'main']);
  assert.equal(write('.agents/hooks.json', {}).status, 0);
});
