import fs from 'node:fs';
import path from 'node:path';
import { AiwsError, writeText } from '../util.js';

/** Where a project's skills live for Codex, OpenCode and Antigravity alike. */
export const SKILLS_DIR = '.agents/skills';
const LOCAL_CLI = 'aiws/adapters/cli';

/** The line that marks a file as written by `aiws sync <target>`; what carries it is the kit's to replace and remove. */
export function generatedNote(target) {
  return `GENERATED by \`aiws sync ${target}\` from aiws/. Do not edit; edit aiws/ and re-sync.`;
}

/**
 * What an agent is told, whatever the tool that runs it: its own instructions, where its skills are, and what
 * checks its writes. `guarded` says whether the tool calls the `aiws guard` hook; without it only diff-scope checks.
 */
export function instructions(ws, agent, { guarded = true } = {}) {
  const en = ws.language === 'en';
  const skills = agent.skills ?? [];
  const files = skills.map((s) => `${SKILLS_DIR}/${s}/SKILL.md`).join(', ');
  const skillNote = skills.length
    ? `\n\n# Skills\n${en ? 'Before you start, read the skills' : 'Trước khi làm, đọc các skill'}: ${files}.`
    : '';
  const checked = guarded
    ? en
      ? 'Every file change is checked by the `aiws guard` hook and `aiws check diff-scope`. A write outside the scope of the phase is blocked or reverted.'
      : 'Mọi thay đổi file bị kiểm tra bởi hook `aiws guard` và `aiws check diff-scope`. Ghi ngoài phạm vi của phase sẽ bị chặn hoặc bị revert.'
    : en
      ? 'Every file change is checked by `aiws check diff-scope`. A write outside the scope of the phase is reverted.'
      : 'Mọi thay đổi file bị kiểm tra bởi `aiws check diff-scope`. Ghi ngoài phạm vi của phase sẽ bị revert.';
  const language = en ? '\n\n# Language\nWrite every document, finding and report in English.' : '';
  return `${agent.body.trim()}${skillNote}\n\n# Enforcement\n${checked}${language}\n`;
}

/** Copies every skill of aiws/ to where the tools read a project's skills; returns what was written. */
export function syncSkills(ws) {
  const written = [];
  for (const name of ws.listSkills()) {
    const to = path.join(ws.root, SKILLS_DIR, name);
    fs.rmSync(to, { recursive: true, force: true });
    fs.cpSync(path.join(ws.aiwsDir, 'skills', name), to, { recursive: true });
    written.push(`${SKILLS_DIR}/${name}/`);
  }
  return written;
}

/**
 * Removes what an earlier sync wrote for an agent that is gone. Only a file that carries the generated note is
 * the kit's to remove: the folder may hold agents of the project's own.
 */
export function removeStale(files, target) {
  const note = generatedNote(target);
  for (const file of files) {
    let text;
    try {
      text = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    if (text.includes(note)) fs.rmSync(file, { force: true });
  }
}

/** Whether the workspace carries its own CLI (the kit repo, or a project that vendors aiws/adapters). */
export function hasLocalCli(ws) {
  return fs.existsSync(path.join(ws.root, LOCAL_CLI, 'bin', 'aiws.js'));
}

/** The path of the workspace's own CLI from a folder `depth` levels below the root, with forward slashes. */
export function localCliFrom(depth) {
  return `${'../'.repeat(depth)}${LOCAL_CLI}/bin/aiws.js`;
}

/**
 * The run side of a tool that `aiws sync` only writes the configuration of. Such a tool is for interactive
 * sessions; `aiws run` drives the adapters that can run headless.
 */
export function interactiveOnly(name) {
  const refuse = () => {
    throw new AiwsError(
      `The ${name} adapter is for interactive sessions: \`aiws sync ${name}\` writes its agents, skills and guard hook, and \`aiws run\` cannot drive it. ` +
        'Set the adapter of the phases to claude or codex in aiws/config/runtime.yaml.'
    );
  };
  return { preflight: refuse, runAgent: refuse };
}

export { writeText };
